/**
 * 将 seed 图写入 IndexedDB（应用初次启动时调用）。
 * 已有数据时不覆盖（幂等）。
 */
export async function initSeedIfEmpty(): Promise<void> {
  const { getDB } = await import("./db");
  const db = getDB();
  const count = await db.nodes.count();
  if (count > 0) return; // 已有数据，不覆盖

  await db.nodes.bulkPut(seedGraph.nodes);
  await db.events.bulkPut(seedGraph.events);
  await db.messages.bulkPut(seedGraph.rawMessages);
}
